// Generates React icon components from assets/icons/*.svg into packages/ui/src/icons/index.tsx.
// Run: corepack pnpm icons   (re-run whenever Malik adds or changes an icon)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "assets/icons");
const out = join(root, "packages/ui/src/icons/index.tsx");

const pascal = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const camelAttr = (a) => a.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const files = readdirSync(src).filter((f) => f.endsWith(".svg")).sort();
const icons = files.map((file) => {
  const svg = readFileSync(join(src, file), "utf8");
  const open = /<svg([^>]*)>/.exec(svg);
  if (!open) throw new Error(`No <svg> in ${file}`);
  const attrs = Object.fromEntries([...open[1].matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
  const inner = svg
    .slice(open.index + open[0].length, svg.lastIndexOf("</svg>"))
    .trim()
    .replace(/\s([a-z]+-[a-z-]+)=/g, (_, a) => ` ${camelAttr(a)}=`)
    .replace(/\sclass=/g, " className=");
  return {
    name: pascal(file.replace(/\.svg$/, "")) + "Icon",
    slug: file.replace(/\.svg$/, ""),
    fill: attrs.fill ?? "none",
    stroke: attrs.stroke ?? (attrs.fill && attrs.fill !== "none" ? undefined : "currentColor"),
    strokeWidth: attrs["stroke-width"],
    inner,
  };
});

const body = icons
  .map((i) => {
    const props = [
      `fill="${i.fill}"`,
      i.stroke ? `stroke="${i.stroke}"` : "",
      i.strokeWidth ? `strokeWidth={${i.strokeWidth}}` : "",
      i.stroke ? `strokeLinecap="round" strokeLinejoin="round"` : "",
    ]
      .filter(Boolean)
      .join(" ");
    return `export function ${i.name}(props: IconProps) {\n  return (\n    <Svg {...props} ${props}>\n      ${i.inner}\n    </Svg>\n  );\n}`;
  })
  .join("\n\n");

const file = `// GENERATED by scripts/build-icons.mjs from assets/icons — do not edit by hand.
import type { ReactNode, SVGProps } from "react";

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children"> {
  /** Pixel size; defaults to 24 (the icon grid). */
  size?: number;
  /** Accessible name. Omit for decorative icons next to visible text. */
  title?: string;
}

function Svg({ size = 24, title, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}

${body}

export const ICON_NAMES = ${JSON.stringify(icons.map((i) => i.slug))} as const;
`;

writeFileSync(out, file);
console.log(`Generated ${icons.length} icons → ${out}`);
